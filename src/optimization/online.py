"""Archive-free, prequentially checked promotion with exact SH fallback.

No model/archive files are loaded. Only terminal observations generated by this
search label feature snapshots captured at an earlier rung. Check architectures
are never fitted or calibrated; their forecasts are frozen before maturation.
"""
from __future__ import annotations
import hashlib
import json
import math
from pathlib import Path
import time
import numpy as np
from scipy.stats import spearmanr
from sklearn.ensemble import RandomForestRegressor
from src.optimization.bpso import BPSO, SwarmSettings
from src.optimization.curve_predictor import curve_features, raw_prediction
from src.utils.core import digest, save_json


class OnlinePredictor:
    def __init__(self, codec, settings=None):
        self.codec = codec
        self.settings = settings or {}
        self.records = {}
        self.models = {}
        self.preparation_seconds = 0.
        self.prediction_seconds = 0.
        self.fit_count = 0
        self.fit_audits = []

    def partition(self, key):
        token = hashlib.sha256(('online-split-1181:' + key).encode()).digest()
        value = int.from_bytes(token[:8], 'big') % 10
        return 'fit' if value < 5 else 'calibration' if value < 7 else 'check'

    def capture(self, architecture, trajectory, budget, previous_budget=0):
        began = time.perf_counter()
        key = digest(architecture)
        record = self.records.setdefault(key, {'architecture': architecture, 'partition': self.partition(key),
                                               'snapshots': {}, 'forecasts': {}, 'target': None})
        observed = [r for r in trajectory if r['epoch'] <= budget]
        features = curve_features(architecture, observed, budget, self.codec)
        # Incremental costs are known at query time; later training is excluded.
        incremental = sum(r['training_seconds'] + r['validation_seconds'] for r in observed if r['epoch'] > previous_budget)
        prefix = sum(r['training_seconds'] + r['validation_seconds'] for r in observed)
        features = np.r_[features, np.log1p(incremental), np.log1p(prefix)]
        current = next(r['macro_f1'] for r in observed if r['epoch'] == budget)
        record['snapshots'].setdefault(budget, {'features': features.tolist(), 'observed_f1': current,
                                              'incremental_seconds': incremental, 'prefix_seconds': prefix})
        self.preparation_seconds += time.perf_counter() - began
        return key

    def label(self, key, target):
        if key in self.records:
            if self.records[key]['target'] is not None and self.records[key]['target'] != target:
                raise ValueError('Conflicting target for the same architecture and search seed')
            self.records[key]['target'] = float(target)

    def prepare(self, budget, query_ids):
        began = time.perf_counter()
        eligible = {key: r for key, r in self.records.items()
                    if r['target'] is not None and budget in r['snapshots'] and key not in query_ids}
        fit = sorted(k for k, r in eligible.items() if r['partition'] == 'fit')
        cal = sorted(k for k, r in eligible.items() if r['partition'] == 'calibration')
        info = {'budget': budget, 'mature_architectures': sum(r['target'] is not None for r in self.records.values()),
                'fit_architectures': len(fit), 'calibration_architectures': len(cal), 'allowed': False}
        if len(fit) < self.settings.get('min_fit', 6) or len(cal) < self.settings.get('min_calibration', 4):
            info['reason'] = 'insufficient_fit_or_calibration_architectures'
            self.preparation_seconds += time.perf_counter() - began
            return None, info
        signature = (budget, tuple(fit), tuple(cal))
        if signature not in self.models:
            forest = RandomForestRegressor(n_estimators=24, max_depth=4, min_samples_leaf=2,
                                           max_features=.75, random_state=1181 + budget, n_jobs=1)
            forest.fit([eligible[k]['snapshots'][budget]['features'] for k in fit], [eligible[k]['target'] for k in fit])
            mean, scale = raw_prediction(forest, [eligible[k]['snapshots'][budget]['features'] for k in cal])
            residuals = np.sort(np.abs(np.array([eligible[k]['target'] for k in cal]) - mean) / scale)
            index = math.ceil((len(cal) + 1) * .8)
            q = float(residuals[index - 1]) if index <= len(cal) else None
            if q is None:
                info['reason'] = 'insufficient_corrected_calibration_quantile'
                self.preparation_seconds += time.perf_counter() - began
                return None, info
            self.models[signature] = {'forest': forest, 'q': q, 'fit_ids': fit, 'calibration_ids': cal}
            self.fit_count += 1
            self.fit_audits.append({'budget': budget, 'fit_ids': fit, 'calibration_ids': cal, 'excluded_query_ids': sorted(query_ids)})
        model = self.models[signature]
        # True out-of-time checks: only forecasts frozen before target arrival.
        checks = [r for r in self.records.values() if r['partition'] == 'check' and r['target'] is not None and budget in r['forecasts']]
        checks = checks[-self.settings.get('check_window', 20):]
        info['prequential_check_architectures'] = len(checks)
        if len(checks) < self.settings.get('min_checks', 4):
            info['reason'] = 'insufficient_out_of_time_check_architectures'
        else:
            y = np.array([r['target'] for r in checks])
            predicted = np.array([r['forecasts'][budget]['mean'] for r in checks])
            observed = np.array([r['snapshots'][budget]['observed_f1'] for r in checks])
            mae, baseline = float(np.mean(abs(y - predicted))), float(np.mean(abs(y - observed)))
            lower = np.array([r['forecasts'][budget]['lower'] for r in checks])
            upper = np.array([r['forecasts'][budget]['upper'] for r in checks])
            coverage, width = float(np.mean((lower <= y) & (y <= upper))), float(np.mean(upper - lower))
            rho = float(spearmanr(predicted, y).statistic) if np.ptp(y) >= .02 and np.ptp(predicted) > 1e-10 else None
            point_ok = (mae <= self.settings.get('max_mae', .08) and
                        mae <= .9 * baseline and baseline - mae >= .005 and rho is not None and rho >= .3)
            uncertainty_ok = coverage >= .75 and width <= self.settings.get('max_width', .3)
            info.update(mae=mae, observed_rank_baseline_mae=baseline, spearman=rho,
                        coverage=coverage, mean_width=width, point_gate_passed=point_ok,
                        uncertainty_gate_passed=uncertainty_ok)
            require_uncertainty = self.settings.get('mode', 'full') != 'prediction'
            info['allowed'] = bool(point_ok and (uncertainty_ok or not require_uncertainty))
            info['reason'] = 'passed' if info['allowed'] else 'inadequate_prequential_accuracy_or_calibration'
        self.preparation_seconds += time.perf_counter() - began
        return model, info

    def predict(self, key, budget, model):
        began = time.perf_counter()
        if key in model['fit_ids'] or key in model['calibration_ids']:
            raise ValueError('A query architecture entered its own predictor development set')
        record = self.records[key]
        mean, scale = raw_prediction(model['forest'], [record['snapshots'][budget]['features']])
        radius = min(1., model['q'] * float(scale[0]))
        answer = {'mean': float(mean[0]), 'radius': radius, 'lower': max(0., float(mean[0]) - radius),
                  'upper': min(1., float(mean[0]) + radius)}
        if record['partition'] == 'check' and record['target'] is None:
            record['forecasts'].setdefault(budget, dict(answer, fit_ids=model['fit_ids'], calibration_ids=model['calibration_ids'],
                                                        made_before_target=True))
        self.prediction_seconds += time.perf_counter() - began
        return answer


def archive_free_search(evaluator, codec, cfg):
    search = cfg['search']
    if search.get('predictor_bundle') or search.get('predictor_sha256'):
        raise ValueError('Archive-free search must not receive an offline predictor bundle')
    budgets = search.get('budgets', [3, 10, 30])
    if not budgets or budgets != sorted(set(budgets)) or budgets[-1] != search['epochs']:
        raise ValueError('Invalid archive-free fidelities')
    settings = SwarmSettings(**{k: v for k, v in search.items() if k in SwarmSettings.__dataclass_fields__})
    swarm = BPSO(codec.length, settings, cfg.get('seed', 42))
    online = OnlinePredictor(codec, search.get('online', {}))
    decisions, finalists = [], []
    pending = None
    started = time.perf_counter()
    try:
        for generation in range(settings.generations):
            candidates = list(swarm.position)
            active = list(range(len(candidates)))
            terminal_scores = {}
            for level, budget in enumerate(budgets):
                scores, keys = {}, {}
                for i in active:
                    architecture = codec.decode(candidates[i])
                    key = digest(architecture)
                    pending = (key, candidates[i], budget)
                    score = evaluator.evaluate(candidates[i], budget)
                    scores[i], keys[i] = score, key
                    if not np.isfinite(score):
                        continue
                    if level == len(budgets) - 1:
                        online.label(key, score)
                        terminal_scores[i] = score
                        finalists.append({'architecture': architecture, 'fitness': score, 'completed_budget': budget})
                    else:
                        path = evaluator.candidate_path(architecture, evaluator.seed) / 'trajectory.json'
                        trajectory = json.loads(path.read_text())
                        online.capture(architecture, trajectory, budget, budgets[level - 1] if level else 0)
                if level == len(budgets) - 1:
                    break
                count = max(1, len(active) // search.get('eta', 3))
                # Identical positions, tie handling and quotas to ordinary SH until
                # independently checked predictions are useful.
                selected = sorted(active, key=lambda i: (-scores[i], i))[:count]
                query_ids = {keys[i] for i in active if np.isfinite(scores[i])}
                model, gate = online.prepare(budget, query_ids)
                predictions = {}
                if model is not None:
                    for i in active:
                        if np.isfinite(scores[i]):
                            predictions[i] = online.predict(keys[i], budget, model)
                applied = gate['allowed'] and len(predictions) == len(active)
                mode = search.get('online', {}).get('mode', 'full')
                if applied and mode != 'prediction' and any(p['upper'] - p['lower'] > search.get('online', {}).get('max_width', .3) for p in predictions.values()):
                    applied = False
                    gate['reason'] = 'current_prediction_intervals_too_wide'
                costs, priority = [], {}
                if applied:
                    costs = []
                    for i in active:
                        architecture = codec.decode(candidates[i])
                        rows = json.loads((evaluator.candidate_path(architecture, evaluator.seed) / 'trajectory.json').read_text())
                        before = [r for r in rows if r['epoch'] <= budget]
                        train_cost = np.mean([r['training_seconds'] for r in before]) * (budgets[-1] - budget)
                        val = [r['validation_seconds'] for r in before if r.get('macro_f1') is not None]
                        schedule = cfg.get('runtime', {}).get('validation_epochs')
                        checks = sum(budget < e <= budgets[-1] for e in set(schedule + [budgets[-1]])) if schedule else budgets[-1] - budget
                        costs.append(float(train_cost + np.mean(val) * checks))
                    normalizer = max(1e-9, float(np.median(costs)))
                    priority = {i: predictions[i]['mean'] + (0. if mode == 'prediction' else .1 * predictions[i]['radius'])
                                   - (.05 * costs[j] / normalizer if mode == 'full' else 0.) for j, i in enumerate(active)}
                    selected = sorted(active, key=lambda i: (-priority[i], i))[:count]
                decisions.append({'generation': generation, 'budget': budget, 'active_indices': active.copy(),
                                  'selected_indices': selected, 'prediction_applied': bool(applied), 'gate': gate,
                                  'predictions': {str(i): p for i, p in predictions.items()},
                                  'expected_remaining_seconds': {str(i): costs[j] for j, i in enumerate(active)} if applied else {},
                                  'priority': {str(i): v for i, v in priority.items()}})
                active = selected
            swarm.tell(np.asarray([terminal_scores.get(i, -np.inf) for i in range(settings.population)]))
            swarm.step()  # No extra restart alters the SH fallback trajectory.
    finally:
        if pending is not None and pending[2] == budgets[-1]:
            key, bits, budget = pending
            for event in reversed(evaluator.events):
                if event.get('fitness') is not None and event.get('completed_budget') == budget and digest(event['architecture']) == key:
                    online.label(key, event['fitness'])
                    break
        save_json(evaluator.output / 'online_decisions.json', decisions)
        save_json(evaluator.output / 'online_observations.json', online.records)
        save_json(evaluator.output / 'online_fit_audit.json', online.fit_audits)
        save_json(evaluator.output / 'online_summary.json', {'predictor_preparation_seconds': online.preparation_seconds,
                  'predictor_inference_seconds': online.prediction_seconds, 'cpu_fit_count': online.fit_count,
                  'mature_architectures': sum(r['target'] is not None for r in online.records.values()),
                  'prediction_applied_decisions': sum(r['prediction_applied'] for r in decisions),
                  'fallback_decisions': sum(not r['prediction_applied'] for r in decisions),
                  'separately_trained_gpu_archive_seconds': 0., 'total_scheduler_seconds': time.perf_counter() - started})
        save_json(evaluator.output / 'adaptive_state.json', {'finalists': finalists})
    return max(finalists, key=lambda r: r['fitness']) if finalists else None
